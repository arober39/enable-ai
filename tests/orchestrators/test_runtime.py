_REQUIRED_SPAN_NAMES: tuple[str, ...] = (
    "support_orchestrator.handle_inquiry",
    "support_orchestrator.fetch_ai_config",
    "support_orchestrator.classify_intent",
    "support_orchestrator.knowledge_base.search",
    "support_orchestrator.draft_response",
    "support_orchestrator.build_handoff",
    "support_orchestrator.emit_events",
)


def test_expected_span_names_declared() -> None:
    obs = importlib.import_module("orchestrators.support.observability")
    for name in _REQUIRED_SPAN_NAMES:
        assert name in obs.EXPECTED_SPAN_NAMES, f"missing span: {name}"


def test_orchestrator_py_references_each_expected_span() -> None:
    from pathlib import Path

    orch_py = (
        Path(__file__).resolve().parents[2]
        / "orchestrators"
        / "support"
        / "orchestrator.py"
    ).read_text(encoding="utf-8")
    for name in _REQUIRED_SPAN_NAMES:
        assert name in orch_py, f"orchestrator.py doesn't emit span: {name}"


