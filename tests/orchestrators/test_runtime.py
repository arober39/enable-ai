"""Tests for the generated support orchestrator runtime.

Phase 7.3 — these tests run against the actual generated tree under
``orchestrators/support/`` (regenerated by ``tests/conftest.py`` if
missing). They never hit a live LLM — the orchestrator runs in demo mode
(stub classifier, stub draft, stub LD events) by virtue of
``ENABLE_AI_DEMO_MODE=true`` being the default.

What's covered:

  - The generated package imports cleanly.
  - The observability module declares the expected span names.
  - ``orchestrator.py`` references each expected span name (so a future
    refactor that drops a span instrumentation point is caught here).
  - The four documented intent classes produce the documented
    ``action_taken`` against fixture inquiries.
  - Successful and error-path responses conform to ``SupportResponse``.
"""

from __future__ import annotations

import importlib

import pytest


@pytest.fixture(autouse=True)
def _demo_mode_on(monkeypatch: pytest.MonkeyPatch) -> None:
    """Force demo mode for runtime tests — no real LLM / LD calls."""
    monkeypatch.setenv("ENABLE_AI_DEMO_MODE", "true")
    monkeypatch.delenv("ANTHROPIC_API_KEY", raising=False)
    monkeypatch.delenv("LAUNCHDARKLY_SDK_KEY", raising=False)


