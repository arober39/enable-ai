async def test_handle_inquiry_response_shape() -> None:
    """Whatever intent, the response always has these fields with valid types."""
    mod = importlib.import_module("orchestrators.support.orchestrator")
    inq = mod.Inquiry(
        subject="Generic",
        body="Just touching base.",
        customer_id="CUST-014",
    )
    response = await mod.handle_inquiry(inq)
    # The Pydantic model validates these for us; here we just probe the shape.
    assert response.intent in {"FAQ", "REFUND", "ESCALATION", "STATUS", "OTHER"}
    assert isinstance(response.draft_reply, str)
    assert 0.0 <= response.confidence <= 1.0
    assert isinstance(response.action_taken, str)
    assert isinstance(response.citations, list)
    assert isinstance(response.escalated, bool)
    # error is None in the success path
    assert response.error is None
