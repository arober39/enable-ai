async def test_handle_inquiry_classifies_refund() -> None:
    mod = importlib.import_module("orchestrators.support.orchestrator")
    inq = mod.Inquiry(
        subject="Cancellation request",
        body="I need to cancel and would like a refund.",
        customer_id="CUST-009",
    )
    response = await mod.handle_inquiry(inq, request_id="test-refund-1")
    assert response.intent == "REFUND"
    assert response.action_taken == "auto_drafted_for_review"
    assert response.escalated is False
    assert response.citations  # refund replies cite policy
    assert response.error is None


